-- 0017_flows: WhatsApp Flows (P4-03). A flow is a form a company designs as Flow JSON and sends in
-- a chat; WhatsApp shows it natively and returns the answers when the customer completes it
-- (research M-097 to M-107, M-161 to M-168). HyFib keeps the draft and everything the company
-- decides about it; Meta holds the uploaded and published flow, reached only by the worker. Flows
-- that fetch data while they are open call HyFib's data endpoint, which decrypts the request with
-- the WhatsApp account's key and forwards it to the company's own endpoint.

-- Encryption keys -----------------------------------------------------------------------------------
-- One RSA key pair per WhatsApp account, generated by the worker. The public key is uploaded to every
-- number of the account (Meta keeps one key per number, M-164); the private key is stored only
-- encrypted with the keyring and bound to its row. During a rotation the previous key still opens
-- requests from clients that have not refreshed yet; a retired key keeps no private key.
CREATE TABLE app.flow_keys (
  id uuid PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES app.tenants (id),
  whatsapp_account_id uuid NOT NULL,
  public_key_pem text NOT NULL CHECK (char_length(public_key_pem) BETWEEN 200 AND 2000),
  fingerprint text NOT NULL CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
  private_key_ciphertext text CHECK (char_length(private_key_ciphertext) <= 8000),
  state text NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'previous', 'retired')),
  created_at timestamptz NOT NULL DEFAULT now(),
  replaced_at timestamptz,
  retired_at timestamptz,
  CONSTRAINT flow_keys_tenant_id_id_uq UNIQUE (tenant_id, id),
  CONSTRAINT flow_keys_account_fk FOREIGN KEY (tenant_id, whatsapp_account_id)
    REFERENCES app.whatsapp_accounts (tenant_id, id),
  CONSTRAINT flow_keys_private CHECK ((state = 'retired') = (private_key_ciphertext IS NULL))
);
CREATE UNIQUE INDEX flow_keys_active_uq ON app.flow_keys (tenant_id, whatsapp_account_id)
  WHERE state = 'active';
CREATE UNIQUE INDEX flow_keys_previous_uq ON app.flow_keys (tenant_id, whatsapp_account_id)
  WHERE state = 'previous';

-- Where each key was uploaded, and what Meta says about it (VALID or MISMATCH).
CREATE TABLE app.flow_key_uploads (
  id uuid PRIMARY KEY,
  tenant_id uuid NOT NULL,
  key_id uuid NOT NULL,
  channel_account_id uuid NOT NULL,
  state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'uploaded', 'failed')),
  signature_status text CHECK (signature_status IN ('VALID', 'MISMATCH')),
  error_code text CHECK (char_length(error_code) <= 64),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  uploaded_at timestamptz,
  checked_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flow_key_uploads_tenant_id_id_uq UNIQUE (tenant_id, id),
  CONSTRAINT flow_key_uploads_uq UNIQUE (tenant_id, key_id, channel_account_id),
  CONSTRAINT flow_key_uploads_key_fk FOREIGN KEY (tenant_id, key_id)
    REFERENCES app.flow_keys (tenant_id, id),
  CONSTRAINT flow_key_uploads_channel_fk FOREIGN KEY (tenant_id, channel_account_id)
    REFERENCES app.channel_accounts (tenant_id, id)
);
CREATE TRIGGER flow_key_uploads_touch BEFORE UPDATE ON app.flow_key_uploads
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

-- Flows ---------------------------------------------------------------------------------------------
-- The draft (Flow JSON checked by HyFib; Meta validates it again on upload), what Meta reports, and
-- the one operation the worker performs against Meta next, written before the call (sync_op and
-- sync_state), so a crash or a lost response is resolved by the next attempt instead of repeated.
-- A published flow cannot change at Meta: editing it starts a new draft (derived_from_flow_id).
CREATE TABLE app.flows (
  id uuid PRIMARY KEY,
  tenant_id uuid NOT NULL REFERENCES app.tenants (id),
  whatsapp_account_id uuid NOT NULL,
  public_id text NOT NULL CHECK (public_id ~ '^[a-z2-7]{16}$'),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
  categories text[] NOT NULL CHECK (cardinality(categories) BETWEEN 1 AND 8 AND categories <@ ARRAY[
    'SIGN_UP', 'SIGN_IN', 'APPOINTMENT_BOOKING', 'LEAD_GENERATION', 'CONTACT_US', 'CUSTOMER_SUPPORT',
    'SURVEY', 'OTHER']::text[]),
  -- The Flow JSON exactly as the member wrote it (Meta's validation errors refer to its lines).
  flow_json text NOT NULL CHECK (char_length(flow_json) BETWEEN 2 AND 262144),
  json_version text NOT NULL CHECK (json_version ~ '^[0-9]{1,2}\.[0-9]{1,2}$'),
  data_api_version text CHECK (data_api_version ~ '^[0-9]{1,2}\.[0-9]{1,2}$'),
  first_screen text NOT NULL CHECK (first_screen ~ '^[A-Za-z0-9_]{1,100}$'),
  answer_keys text[] NOT NULL DEFAULT '{}' CHECK (cardinality(answer_keys) <= 100),
  answer_mapping jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(answer_mapping) = 'array'
    AND jsonb_array_length(answer_mapping) <= 50),
  -- The company's endpoint for flows that exchange data (an allowed domain, P4-02), and the name of
  -- the secret sent to it as a bearer token. The service requires https:// (http:// only for local
  -- test targets, like web requests).
  endpoint_url text CHECK (char_length(endpoint_url) <= 2000 AND endpoint_url ~ '^https?://'),
  endpoint_secret_name text CHECK (endpoint_secret_name ~ '^[a-z][a-z0-9_]{0,39}$'),
  derived_from_flow_id uuid,
  meta_flow_id text CHECK (meta_flow_id ~ '^[A-Za-z0-9_-]{1,64}$'),
  meta_status text CHECK (meta_status IN ('DRAFT', 'PUBLISHED', 'DEPRECATED', 'BLOCKED', 'THROTTLED')),
  uploaded_json_sha256 text CHECK (uploaded_json_sha256 ~ '^[0-9a-f]{64}$'),
  validation_errors jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(validation_errors) = 'array'
    AND pg_column_size(validation_errors) <= 65536),
  health jsonb CHECK (pg_column_size(health) <= 16384),
  preview_url text CHECK (char_length(preview_url) <= 2000 AND preview_url ~ '^https://'),
  preview_expires_at timestamptz,
  sync_op text CHECK (sync_op IN ('create', 'upload', 'publish', 'deprecate', 'delete', 'refresh')),
  sync_state text NOT NULL DEFAULT 'idle' CHECK (sync_state IN ('idle', 'queued', 'running', 'failed')),
  sync_error text CHECK (char_length(sync_error) <= 1000),
  sync_requested_at timestamptz,
  synced_at timestamptz,
  archived_at timestamptz,
  version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
  created_by_membership_id uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flows_tenant_id_id_uq UNIQUE (tenant_id, id),
  CONSTRAINT flows_public_id_uq UNIQUE (public_id),
  CONSTRAINT flows_meta_uq UNIQUE (tenant_id, meta_flow_id),
  CONSTRAINT flows_op CHECK ((sync_state = 'idle') = (sync_op IS NULL)),
  CONSTRAINT flows_endpoint CHECK (endpoint_secret_name IS NULL OR endpoint_url IS NOT NULL),
  CONSTRAINT flows_account_fk FOREIGN KEY (tenant_id, whatsapp_account_id)
    REFERENCES app.whatsapp_accounts (tenant_id, id),
  CONSTRAINT flows_derived_fk FOREIGN KEY (tenant_id, derived_from_flow_id)
    REFERENCES app.flows (tenant_id, id),
  CONSTRAINT flows_created_by_fk FOREIGN KEY (tenant_id, created_by_membership_id)
    REFERENCES app.memberships (tenant_id, id)
);
CREATE UNIQUE INDEX flows_name_uq ON app.flows (tenant_id, whatsapp_account_id, lower(name))
  WHERE archived_at IS NULL;
CREATE INDEX flows_list_idx ON app.flows (tenant_id, archived_at, created_at DESC);
CREATE INDEX flows_sync_idx ON app.flows (sync_requested_at) WHERE sync_state IN ('queued', 'running');
CREATE TRIGGER flows_touch BEFORE UPDATE ON app.flows
  FOR EACH ROW EXECUTE FUNCTION app.touch_updated_at();

